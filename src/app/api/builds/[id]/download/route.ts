import { createReadStream } from "node:fs";
import { stat } from "node:fs/promises";
import { Readable } from "node:stream";
import { errorResponse, json } from "@/lib/api-helpers";
import type { ApiError } from "@/lib/build-types";
import { getBuildManager } from "@/lib/build-manager";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/** Streams the finished APK. Only completed jobs have an artifact; the path comes from the registry, never from the URL. */
export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id } = await params;
    const artifact = getBuildManager().artifact(id);
    if (!artifact) {
      return json<ApiError>({ error: "No download is available for this build (not finished, failed, or expired)." }, 404);
    }

    let size: number;
    try {
      size = (await stat(artifact.filePath)).size;
    } catch {
      return json<ApiError>({ error: "The APK is no longer available." }, 404);
    }

    const body = Readable.toWeb(createReadStream(artifact.filePath)) as ReadableStream<Uint8Array>;
    return new Response(body, {
      headers: {
        "Content-Type": artifact.contentType,
        "Content-Length": String(size),
        // fileName is generated by the server from an ASCII slug, never taken from the request.
        "Content-Disposition": `attachment; filename="${artifact.fileName}"`,
        "X-Content-Type-Options": "nosniff",
        "Cache-Control": "no-store",
      },
    });
  } catch (error) {
    return errorResponse(error);
  }
}
